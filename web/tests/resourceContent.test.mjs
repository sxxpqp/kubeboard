import assert from 'node:assert/strict'
import { resourceObject, resourceSections, environmentContainers } from '../src/utils/resourceContent.js'
assert.deepEqual(resourceObject({ rawYaml: '[' }), {})
const pv = resourceSections({ kind: 'PersistentVolume', spec: { capacity: { storage: '10Gi' }, persistentVolumeReclaimPolicy: 'Retain', claimRef: { name: 'data', namespace: 'default' } }, status: { phase: 'Bound' } })
assert.equal(pv[0].rows.find(r => r.name === '容量').value, '10Gi')
assert.equal(pv[0].rows.find(r => r.name === '回收策略').value, 'Retain')
const ds = resourceSections({ kind: 'DaemonSet', spec: {}, status: { desiredNumberScheduled: 3, numberReady: 2 } })
assert.equal(ds[0].rows[0].value, '3')
assert.equal(ds[0].rows.some(r => r.name === '期望副本'), false)
const secret = resourceSections({ kind: 'Secret', data: { password: 'sensitive' } })
assert.equal(JSON.stringify(secret).includes('sensitive'), false)
const env = environmentContainers({ spec: { containers: [{ name: 'app', env: [{ name: 'TOKEN', valueFrom: { secretKeyRef: { name: 'credentials', key: 'token' } } }], envFrom: [{ configMapRef: { name: 'settings' } }] }] } })
assert.equal(env[0].rows.length, 2)
assert.match(env[0].rows[0].value, /credentials/)
const pvc = resourceSections({ kind: 'PersistentVolumeClaim', spec: { resources: { requests: { storage: '5Gi' } } }, status: { capacity: { storage: '10Gi' } } })
assert.equal(pvc[0].rows.find(r => r.name === '申请容量').value, '5Gi')
assert.equal(pvc[0].rows.find(r => r.name === '实际容量').value, '10Gi')
console.log('资源内容转换检查通过')
const { conditionType } = await import('../src/utils/resourceContent.js')
assert.equal(conditionType({ type: 'MemoryPressure', status: 'False' }), 'success')
assert.equal(conditionType({ type: 'MemoryPressure', status: 'True' }), 'warning')
assert.equal(conditionType({ type: 'Ready', status: 'False' }), 'warning')
assert.equal(conditionType({ type: 'Ready', status: 'Unknown' }), 'info')
const pod = resourceSections({ kind: 'Pod', spec: {}, status: { containerStatuses: [{ name: 'app', state: { waiting: { reason: 'CrashLoopBackOff' } }, restartCount: 3 }] } })
assert.equal(pod[0].rows[0].reason, 'CrashLoopBackOff')
assert.equal(pod[0].rows[0].restarts, 3)
const policy = resourceSections({ kind: 'NetworkPolicy', spec: { ingress: [{ from: [{ namespaceSelector: { matchLabels: { team: 'ops' } }, podSelector: { matchLabels: { app: 'api' } } }], ports: [{ port: 443 }] }] } })
assert.match(policy[1].rows[0].peers, /且/)
assert.equal(policy[1].rows[0].ports, 'TCP/443')
